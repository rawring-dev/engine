    try expectTranspile(std.testing.allocator,
        \\add <- (a: i32, b: i32) -> i32 = a + b
    ,
        \\// Generated by the engine7 e7s -> Slang transpiler. Do not edit.
        \\// Source: main.e7
        \\module main;
        \\
        \\int add(int a, int b) {
        \\    return (a + b);
