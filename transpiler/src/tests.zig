//! End-to-end tests for the e7s -> Slang transpiler.

const std = @import("std");
const api = @import("project.zig");
const session = @import("session.zig");

const TestCase = struct {
    name: []const u8,
    source: []const u8,
    expected: []const u8,
};

fn expectTranspile(allocator: std.mem.Allocator, source: []const u8, expected: []const u8) !void {
    var result = try api.transpileModules(allocator, &.{
        .{ .name = "main", .source = source, .is_root = true },
    }, .{});
    switch (result) {
        .ok => |files| {
            defer api.freeResult(allocator, &result);
            try std.testing.expectEqual(@as(usize, 1), files.len);
            try std.testing.expectEqualStrings(expected, files[0].source);
        },
        .diagnostics => |diagnostics| {
            defer api.freeResult(allocator, &result);
            for (diagnostics) |diagnostic| {
                std.debug.print("unexpected diagnostic: {d}:{d}: {s}\n", .{
                    diagnostic.line,
                    diagnostic.column,
                    diagnostic.message,
                });
            }
            return error.UnexpectedDiagnostic;
        },
    }
}

fn expectDiagnostic(allocator: std.mem.Allocator, source: []const u8, needle: []const u8) !void {
    var result = try api.transpileModules(allocator, &.{
        .{ .name = "main", .source = source, .is_root = true },
    }, .{});
    switch (result) {
        .ok => {
            api.freeResult(allocator, &result);
            return error.ExpectedDiagnostic;
        },
        .diagnostics => |diagnostics| {
            defer api.freeResult(allocator, &result);
            try std.testing.expect(diagnostics.len > 0);
            var found = false;
            for (diagnostics) |diagnostic| {
                if (std.mem.indexOf(u8, diagnostic.message, needle) != null) found = true;
            }
            if (!found) {
                for (diagnostics) |diagnostic| {
                    std.debug.print("diagnostic: {s}\n", .{diagnostic.message});
                }
                return error.WrongDiagnostic;
            }
        },
    }
}

