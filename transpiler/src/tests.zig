fn expectContains(allocator: std.mem.Allocator, source: []const u8, needles: []const []const u8) !void {
    var result = try api.transpileModules(allocator, &.{
        .{ .name = "main", .source = source, .is_root = true },
    }, .{});
    switch (result) {
        .ok => |files| {
            defer api.freeResult(allocator, &result);
            for (needles) |needle| {
                if (std.mem.indexOf(u8, files[0].source, needle) == null) {
                    std.debug.print("missing `{s}` in:\n{s}\n", .{ needle, files[0].source });
                    return error.MissingOutput;
                }
            }
        },
        .diagnostics => |diagnostics| {
            defer api.freeResult(allocator, &result);
            for (diagnostics) |diagnostic| {
                std.debug.print("unexpected diagnostic: {s}\n", .{diagnostic.message});
            }
            return error.UnexpectedDiagnostic;
        },
    }
}

test "transpiles traits, impl extensions, and generic constraints" {
    try expectContains(
        std.testing.allocator,
        \\trait IThing
        \\    get <- (&self) -> f32
        \\    reset <- (&mut self) -> nil
        \\
        \\Thing <- struct
        \\    value: f32
        \\
        \\impl IThing for Thing:
        \\    get <- (this: &Thing) -> f32 = this.value
        \\    reset <- (this: &mut Thing) -> nil:
        \\        this.value = 0.0
        \\
        \\impl Thing:
        \\    make <- () -> Thing = Thing{value: 1.0}
        \\
        \\pick<T> <- (a: T, b: T) -> T where T: IThing = a
    ,
        &.{
            "interface IThing {",
            "float get();",
            "[mutating] void reset();",
            "extension Thing : IThing {",
            "float get() {",
            "[mutating] void reset() {",
            "static Thing make() {",
            "T pick<T : IThing>(T a, T b) {",
        },
    );
}

test "transpiles multi-module projects" {
    var result = try api.transpileModules(std.testing.allocator, &.{
        .{ .name = "main", .source =
        \\mod math
        \\use math::*;
        \\
        \\@binding(0, 0)
        \\scene: Params
        \\
        \\Params <- struct
        \\    colour: math::Colour
        \\
        \\@fragment
        \\main <- (c: math::Colour) -> [f32; 4]:
        \\    ret [c.r, c.g, c.b, 1.0]
        , .is_root = true },
        .{ .name = "math", .source =
        \\pub Colour <- struct
        \\    r: f32
        \\    g: f32
        \\    b: f32
        \\
        \\pub PI := 3.14159265
        , .is_root = false },
    }, .{});
    defer api.freeResult(std.testing.allocator, &result);

    const files = switch (result) {
        .ok => |files| files,
        .diagnostics => |diagnostics| {
            for (diagnostics) |diagnostic| {
                std.debug.print("unexpected diagnostic: {s}\n", .{diagnostic.message});
            }
            return error.UnexpectedDiagnostic;
        },
    };
    try std.testing.expectEqual(@as(usize, 2), files.len);

    try std.testing.expect(std.mem.indexOf(u8, files[0].source, "import math;") != null);
    try std.testing.expect(std.mem.indexOf(u8, files[0].source, "Colour colour;") != null);
    try std.testing.expect(std.mem.indexOf(u8, files[0].source, "c.r, c.g, c.b") != null);
    try std.testing.expect(std.mem.indexOf(u8, files[1].source, "public struct Colour {") != null);
    try std.testing.expect(std.mem.indexOf(u8, files[1].source, "public static const float PI") != null);
}

