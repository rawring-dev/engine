test "transpiles control flow, match, and vector/matrix indexing" {
    try expectContains(
        std.testing.allocator,
        \\Mode <- enum
        \\    Off
        \\    On
        \\
        \\sum_to <- (n: i32) -> i32:
        \\    total: i32
        \\    total = 0
        \\    for i in 0..n:
        \\        total += i
        \\    while total > 1:
        \\        total -= 1
        \\        if total == 5:
        \\            cont
        \\    loop:
        \\        break
        \\    match Mode::Off:
        \\        Mode::On:
        \\            ret 1
        \\        _:
        \\            ret 0
    ,
        &.{
            "enum class Mode {",
            "for (int i = 0; i < n; i += 1) {",
            "while ((total > 1)) {",
            "continue;",
            "for (;;) {",
            "switch (Mode::Off) {",
            "case Mode::On:",
            "default:",
        },
    );
}

